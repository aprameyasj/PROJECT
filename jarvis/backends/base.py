"""Action backends.

The brain talks to a backend, never to the OS directly. Two implementations:

* :class:`~jarvis.backends.desktop.DesktopBackend` — real pyautogui / subprocess
  actions on your machine (Windows, macOS, Linux with a display).
* :class:`~jarvis.backends.sandbox.SandboxBackend` — a simulated desktop used
  when there is no GUI (containers, CI, `JARVIS_DRY_RUN=1`). It keeps a
  coherent virtual machine state so multi-step plans still behave sensibly
  and every action is recorded for the dashboard.

Both expose the same interface, which is what makes JARVIS portable.
"""

from __future__ import annotations

from typing import Any, Protocol, runtime_checkable


@runtime_checkable
class ActionBackend(Protocol):
    name: str
    simulated: bool

    def describe(self) -> dict[str, Any]: ...
    def screen_size(self) -> tuple[int, int]: ...
    def mouse_position(self) -> tuple[int, int]: ...
    def hotkey(self, *keys: str) -> str: ...
    def press(self, key: str, times: int = 1) -> str: ...
    def type_text(self, text: str, interval: float = 0.0) -> str: ...
    def click(self, x: int | None = None, y: int | None = None, button: str = "left", clicks: int = 1) -> str: ...
    def move_mouse(self, x: int, y: int, duration: float = 0.2) -> str: ...
    def scroll(self, amount: int, x: int | None = None, y: int | None = None) -> str: ...
    def screenshot(self, path: str | None = None) -> dict[str, Any]: ...
    def launch_app(self, application: str) -> dict[str, Any]: ...
    def terminate_app(self, application: str, force: bool = False) -> dict[str, Any]: ...
    def list_windows(self) -> list[dict[str, Any]]: ...
    def focus_window(self, title: str) -> str: ...
    def notify(self, title: str, body: str) -> str: ...
    def open_url(self, url: str, application: str | None = None) -> dict[str, Any]: ...
    def shell(self, command: str, cwd: str | None = None, timeout: int = 30) -> dict[str, Any]: ...
    def system_status(self) -> dict[str, Any]: ...
    def set_volume(self, percent: int) -> str: ...
    def media_key(self, action: str) -> str: ...
    def power(self, action: str) -> str: ...
    def clipboard_set(self, text: str) -> str: ...
    def clipboard_get(self) -> str: ...


class BackendUnavailable(RuntimeError):
    """Raised when a backend cannot operate in this environment."""


def get_backend(settings: Any) -> ActionBackend:
    """Factory: pick the right backend for the current environment."""
    from .desktop import DesktopBackend
    from .sandbox import SandboxBackend

    choice = getattr(settings, "backend", "auto")
    if choice == "desktop":
        backend = DesktopBackend(settings)
        if not backend.available:
            # A desktop was requested but there is no GUI (headless container).
            # Fall back rather than dying — but make the downgrade explicit.
            fallback = SandboxBackend(settings)
            fallback.reason = f"desktop backend unavailable ({backend.unavailable_reason}); simulating actions"
            return fallback
        return backend
    return SandboxBackend(settings)


__all__ = ["ActionBackend", "BackendUnavailable", "get_backend"]
